"""Side-by-side eyeball harness for the four providers.

Reads evaluation/eyeball_queries.json, runs each query through every
available provider, and generates evaluation/snippets_eyeball.html — a
human-scannable side-by-side table.

Tolerates provider failures gracefully (Tavily/Brave will fail with
quota errors right now). For each failure renders a "(error: ...)"
cell rather than aborting.

Usage:
    uv run python evaluation/snippet_eyeball.py
    uv run python evaluation/snippet_eyeball.py --providers diy,serper_raw
    uv run python evaluation/snippet_eyeball.py --queries 5
"""
from __future__ import annotations

import argparse
import html
import json
import sys
import time
from pathlib import Path
from typing import List

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))

from agents.tools.search import search, SearchResult


DEFAULT_QUERIES = REPO_ROOT / "evaluation" / "eyeball_queries.json"
DEFAULT_OUTPUT = REPO_ROOT / "evaluation" / "snippets_eyeball.html"
DEFAULT_PROVIDERS = ("tavily", "brave", "serper_raw", "diy")
MAX_RESULTS = 3


def run_one(provider: str, query: str) -> tuple[List[SearchResult] | None, str | None, float]:
    """Run one query through one provider. Returns (results, error, elapsed_s)."""
    t0 = time.perf_counter()
    try:
        results = search(query, provider=provider, max_results=MAX_RESULTS)
        return results, None, time.perf_counter() - t0
    except Exception as exc:  # noqa: BLE001
        return None, f"{type(exc).__name__}: {exc}"[:200], time.perf_counter() - t0


def render_html(rows: list[dict], providers: tuple[str, ...]) -> str:
    """Render rows as an HTML table. rows is a list of {query, results: {provider: ...}}."""
    css = """
    body { font-family: -apple-system, system-ui, sans-serif; margin: 2rem; color: #222; }
    h1 { margin-bottom: 0.5rem; }
    .subtitle { color: #666; margin-bottom: 2rem; }
    table { border-collapse: collapse; width: 100%; table-layout: fixed; }
    th, td { border: 1px solid #ddd; padding: 0.6rem; vertical-align: top;
             font-size: 13px; word-wrap: break-word; }
    th { background: #f5f5f5; text-align: left; position: sticky; top: 0; }
    th.query-col { width: 18%; }
    th.provider-col { width: 20.5%; }
    tr.query-row td { background: #fafafa; }
    .query { font-weight: 600; }
    .err { color: #b00; font-style: italic; }
    .meta { color: #888; font-size: 11px; margin-top: 0.4rem; }
    .result { margin-bottom: 0.6rem; padding-bottom: 0.4rem; border-bottom: 1px dashed #eee; }
    .result:last-child { border-bottom: none; margin-bottom: 0; }
    .title { font-weight: 600; }
    .url a { color: #06c; text-decoration: none; font-size: 11px; }
    .url a:hover { text-decoration: underline; }
    .snippet { color: #333; margin-top: 0.2rem; }
    .score { color: #888; font-size: 11px; margin-left: 0.4em; }
    """
    parts = ["<!DOCTYPE html><html><head><meta charset='utf-8'>"]
    parts.append("<title>DIY-Tavily eyeball comparison</title>")
    parts.append(f"<style>{css}</style></head><body>")
    parts.append("<h1>DIY-Tavily eyeball harness</h1>")
    parts.append("<div class='subtitle'>")
    parts.append(f"Generated by evaluation/snippet_eyeball.py. {len(rows)} queries × ")
    parts.append(f"{len(providers)} providers, top {MAX_RESULTS} results each.")
    parts.append("</div>")
    parts.append("<table>")
    parts.append("<thead><tr><th class='query-col'>Query</th>")
    for p in providers:
        parts.append(f"<th class='provider-col'>{html.escape(p)}</th>")
    parts.append("</tr></thead><tbody>")

    for row in rows:
        parts.append("<tr class='query-row'>")
        parts.append(f"<td><span class='query'>{html.escape(row['query'])}</span></td>")
        for p in providers:
            cell = row["results"].get(p, {})
            parts.append("<td>")
            if cell.get("error"):
                parts.append(f"<div class='err'>{html.escape(cell['error'])}</div>")
            elif cell.get("results") is not None:
                results = cell["results"]
                if not results:
                    parts.append("<div class='err'>(no results)</div>")
                else:
                    for r in results:
                        parts.append("<div class='result'>")
                        parts.append(f"<div class='title'>{html.escape(r.title or '(no title)')}")
                        score_str = f"{r.score:.2f}" if r.score is not None else "—"
                        parts.append(f"<span class='score'>score {score_str}</span></div>")
                        parts.append(f"<div class='url'><a href='{html.escape(r.url)}' "
                                     f"target='_blank'>{html.escape(r.url[:80])}</a></div>")
                        snippet = r.snippet or "(no snippet)"
                        if len(snippet) > 400:
                            snippet = snippet[:400] + "..."
                        parts.append(f"<div class='snippet'>{html.escape(snippet)}</div>")
                        parts.append("</div>")
            parts.append(f"<div class='meta'>{cell.get('elapsed_s', 0.0):.1f}s</div>")
            parts.append("</td>")
        parts.append("</tr>")
    parts.append("</tbody></table></body></html>")
    return "".join(parts)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--queries-file", type=Path, default=DEFAULT_QUERIES)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--providers", default=",".join(DEFAULT_PROVIDERS),
                        help="Comma-separated provider list")
    parser.add_argument("--queries", type=int, default=None,
                        help="Cap on number of queries (for smoke runs)")
    args = parser.parse_args()

    providers = tuple(p.strip() for p in args.providers.split(",") if p.strip())
    queries = json.loads(args.queries_file.read_text(encoding="utf-8"))
    if args.queries:
        queries = queries[: args.queries]

    print(f"Eyeballing {len(queries)} queries × {len(providers)} providers "
          f"= {len(queries) * len(providers)} calls", flush=True)

    rows = []
    for i, q in enumerate(queries, 1):
        row = {"query": q, "results": {}}
        for p in providers:
            print(f"  [{i}/{len(queries)}] {p}: {q[:60]}", end=" ", flush=True)
            results, error, elapsed = run_one(p, q)
            row["results"][p] = {
                "results": results,
                "error": error,
                "elapsed_s": elapsed,
            }
            print(f"({elapsed:.1f}s, {'err' if error else len(results or [])})",
                  flush=True)
        rows.append(row)

    html_out = render_html(rows, providers)
    args.output.write_text(html_out, encoding="utf-8")
    print(f"\nWrote {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
